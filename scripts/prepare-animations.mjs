async function filesIn(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  return (
    await Promise.all(
      entries.map((entry) =>
        entry.isDirectory()
          ? filesIn(path.join(dir, entry.name))
          : path.join(dir, entry.name),
      ),
    )
  ).flat();
}
const files = await filesIn("vfe/Men");
for (const entry of additions) {
  const matches = files.filter(
    (file) => path.basename(file) === `${entry.source}.json`,
  );
  if (matches.length !== 1)
    throw new Error(
      `Expected one exact source for ${entry.id}: ${entry.source}`,
    );
  sources[entry.id] = path.relative("vfe/Men", matches[0]);
}

const rgba = (hex, alpha = 1) => [
  ...hex.match(/\w\w/g).map((c) => parseInt(c, 16) / 255),
  alpha,
];
function themed(color) {
  if (
    !Array.isArray(color) ||
    color.length < 3 ||
    !color.every((n) => typeof n === "number")
  )
    return;
  const [r, g, b, a = 1] = color;
  // Source blue sportswear -> forest; red accents -> sage. Skin is untouched.
  if (b > 0.5 && r < 0.2 && g < 0.2)
    return rgba(b > 0.85 ? "355341" : "243b31", a);
  if (r > 0.5 && g < 0.1 && b < 0.1)
    return rgba(r > 0.88 ? "b5ca8e" : r > 0.7 ? "91aa72" : "738d5f", a);
  // Retain equipment's tonal hierarchy, but move gray into the sage ramp.
  if (Math.max(r, g, b) - Math.min(r, g, b) < 0.025) {
    const v = (r + g + b) / 3;
    return rgba(
      v < 0.2
        ? "243b31"
        : v < 0.45
          ? "52664b"
          : v < 0.65
            ? "829679"
            : v < 0.8
              ? "b5c2a8"
              : "dfe6d5",
      a,
    );
  }
}
function recolor(node) {
  if (!node || typeof node !== "object") return;
  if ((node.ty === "fl" || node.ty === "st") && node.c) {
    if (node.c.a === 0) node.c.k = themed(node.c.k) ?? node.c.k;
    else
      for (const frame of node.c.k)
        for (const field of ["s", "e"])
          if (frame[field]) frame[field] = themed(frame[field]) ?? frame[field];
  }
  for (const value of Object.values(node)) {
    if (Array.isArray(value)) value.forEach(recolor);
    else if (value && typeof value === "object") recolor(value);
  }
}
const destination = "src/assets/animations";
await fs.mkdir(destination, { recursive: true });
for (const [id, source] of Object.entries(sources)) {
  const data = JSON.parse(
    await fs.readFile(path.join("vfe/Men", source), "utf8"),
  );
  if (data.assets?.some((asset) => asset.p))
    throw new Error(`${id}: unexpected image/external asset`);
  recolor(data);
  await fs.writeFile(
    path.join(destination, `${id}.json`),
    JSON.stringify(data),
  );
}
